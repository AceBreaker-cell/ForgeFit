CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name VARCHAR(60) NOT NULL,
    weekly_goal INTEGER NOT NULL DEFAULT 4 CHECK (weekly_goal BETWEEN 1 AND 7),
    target_weight DECIMAL(6,2),
    demo_loaded BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE exercise (
    id BIGINT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    muscle VARCHAR(40) NOT NULL,
    equipment VARCHAR(40) NOT NULL,
    description VARCHAR(500) NOT NULL
);
CREATE TABLE workout_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    name VARCHAR(80) NOT NULL,
    focus VARCHAR(30) NOT NULL,
    notes VARCHAR(1000) NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_plan_user ON workout_plan(user_id);
CREATE TABLE plan_exercise (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL REFERENCES workout_plan(id) ON DELETE CASCADE,
    exercise_id BIGINT NOT NULL REFERENCES exercise(id),
    sets INTEGER NOT NULL CHECK (sets BETWEEN 1 AND 10),
    reps INTEGER NOT NULL CHECK (reps BETWEEN 1 AND 100),
    rest_seconds INTEGER NOT NULL CHECK (rest_seconds BETWEEN 0 AND 600),
    position INTEGER NOT NULL
);
CREATE TABLE training_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    name VARCHAR(80) NOT NULL,
    completed_on DATE NOT NULL,
    duration_minutes INTEGER NOT NULL CHECK (duration_minutes BETWEEN 1 AND 600),
    notes VARCHAR(1000) NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_session_user_date ON training_session(user_id, completed_on);
CREATE TABLE session_set (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES training_session(id) ON DELETE CASCADE,
    exercise_id BIGINT NOT NULL REFERENCES exercise(id),
    reps INTEGER NOT NULL CHECK (reps BETWEEN 1 AND 100),
    weight_kg DECIMAL(7,2) NOT NULL CHECK (weight_kg BETWEEN 0 AND 1500),
    position INTEGER NOT NULL
);
CREATE TABLE weight_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    measured_on DATE NOT NULL,
    weight_kg DECIMAL(6,2) NOT NULL CHECK (weight_kg BETWEEN 20 AND 500),
    UNIQUE(user_id, measured_on)
);
